set1 = {"green", "blue", "yellow", "red", "sky blue"}
set2 = {"dark green", "sky blue", "mustard", "maroon", "blue"}
print("Original Sets : ")
print(set1)
print(set2)
print("Interscetion of both sets : ")
set3 = set1.intersection(set2)
print(set3)
set4 = set1.union(set2)
print("Union of both sets: ")
print(set4)